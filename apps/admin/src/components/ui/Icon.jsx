export const Icon = React.forwardRef(({
  name,
  size,
  className = "",
  style,
  ...props
}, ref) => {
  if (!name) return null;

  // Resolve size from props or Tailwind text-[Npx] class
  let resolvedSize = size;
  if (!resolvedSize && className) {
    const match = className.match(/text-\[(\d+)px\]/);
    if (match) {
      resolvedSize = parseInt(match[1], 10);
    }
  }
  if (!resolvedSize) resolvedSize = 18;

  // Clean class name (strip font ligature class if present)
  const cleanClassName = className.replace(/\bmaterial-symbols-outlined\b/g, "").trim();

  const cleanName = String(name).trim();
  const Component = ICON_MAP[cleanName];

  if (Component) {
    return (
      <Component
        ref={ref}
        size={resolvedSize}
        className={cn("inline-block shrink-0 align-middle", cleanClassName)}
        style={style}
        {...props}
      />
    );
  }

  // Graceful fallback: render CircleDot SVG so raw text is NEVER shown
  return (
    <CircleDot
      ref={ref}
      size={resolvedSize}
      className={cn("inline-block shrink-0 align-middle opacity-60", cleanClassName)}
      style={style}
      {...props}
    />
  );
});

Icon.displayName = "Icon";
