import { expect, test } from "@playwright/test"
import { axe, open, signIn, toast } from "./support.js"

/*
 * Sellers & settlements against the real API (seed/40-marketplace.ts):
 * checking and approving an application, deciding on listings, running a
 * settlement and recording its payout, and the audited bank-number view
 * that finance can open and staff can't.
 */

test.describe.configure({ mode: "serial" })

const section = (page, name) => page.getByRole("tab", { name: new RegExp(`^${name}`) }).click()

test("an application is checked item by item, then approved with a commission override", async ({ page, context }) => {
  await signIn(context, "owner")
  await open(page, "marketplace-sellers")
  await axe(page)
  await page.getByRole("row", { name: /Ravi Crafts/ }).click()
  await expect(page.getByText("BBBPR1234C")).toBeVisible()
  const approve = page.getByRole("button", { name: "Approve seller" })
  await expect(approve).toBeDisabled()
  await expect(page.getByText("Verify the PAN and BANK first.")).toBeVisible()
  await page.getByRole("button", { name: "Mark PAN verified" }).click()
  await expect(toast(page, "PAN verified")).toBeVisible()
  await page.getByRole("button", { name: "Mark Bank account verified" }).click()
  await expect(toast(page, "Bank account verified")).toBeVisible()
  await expect(approve).toBeEnabled()
  await approve.click()
  const dialog = page.getByRole("dialog")
  await dialog.getByLabel("Commission override (%)").fill("12")
  await axe(page)
  await dialog.getByRole("button", { name: "Approve" }).click()
  await expect(toast(page, "Ravi Crafts approved")).toBeVisible()
  await expect(page.getByRole("row", { name: /Ravi Crafts.*Approved/ })).toBeVisible()
  await expect(page.getByText("12% (override)")).toBeVisible()
})

test("listings: one is sent back with a note, the other goes live", async ({ page, context }) => {
  await signIn(context, "owner")
  await open(page, "marketplace-sellers")
  await section(page, "Listings to review")
  await expect(page.getByRole("img", { name: "Ajrakh Cotton Saree, photo 1" })).toBeVisible()
  await expect(page.getByText("KAV-SAR-FREE")).toBeVisible()
  await expect(page.getByText("₹3,499.00")).toBeVisible()
  await axe(page)
  await page.getByRole("button", { name: "Reject Block Print Dupatta" }).click()
  const dialog = page.getByRole("dialog")
  const confirm = dialog.getByRole("button", { name: "Reject" })
  await expect(confirm).toBeDisabled()
  await dialog.getByLabel("What the seller needs to change").fill("Add a photo showing the full length")
  await confirm.click()
  await expect(toast(page, "Block Print Dupatta sent back to the seller")).toBeVisible()
  await page.getByRole("button", { name: "Approve Ajrakh Cotton Saree" }).click()
  await expect(toast(page, "Ajrakh Cotton Saree is live")).toBeVisible()
  await expect(page.getByText("Nothing to review")).toBeVisible()
})

test("finance sees the full bank number after an audit warning; staff can't", async ({ browser }) => {
  const staff = await browser.newContext()
  await signIn(staff, "staff")
  const sp = await staff.newPage()
  await open(sp, "marketplace-sellers")
  await sp.getByRole("row", { name: /Kavya Textiles/ }).click()
  await expect(sp.getByText(/ending 6789/)).toBeVisible()
  await expect(sp.getByRole("button", { name: "Show full number" })).toHaveCount(0)
  await expect(sp.getByText("Only finance and the owner can see the full account number.")).toBeVisible()
  await expect(sp.getByRole("button", { name: "Suspend seller" })).toHaveCount(0)
  await staff.close()

  const finance = await browser.newContext()
  await signIn(finance, "finance")
  const page = await finance.newPage()
  await open(page, "marketplace-sellers")
  await page.getByRole("row", { name: /Kavya Textiles/ }).click()
  await page.getByRole("button", { name: "Show full number" }).click()
  const dialog = page.getByRole("dialog")
  await expect(dialog.getByText(/recorded in the audit log under your name/)).toBeVisible()
  await expect(dialog.getByText("50100123456789")).toHaveCount(0)
  await dialog.getByRole("button", { name: "Show the number" }).click()
  await expect(dialog.getByText("50100123456789")).toBeVisible()
  await axe(page)
  await dialog.getByRole("button", { name: "Done" }).click()
  await expect(page.getByText("50100123456789")).toHaveCount(0)
  // Opened again, the number isn't there until asked for again.
  await page.getByRole("button", { name: "Show full number" }).click()
  await expect(page.getByRole("dialog").getByText("50100123456789")).toHaveCount(0)
  await page.getByRole("dialog").getByRole("button", { name: "Back" }).click()
  await finance.close()
})

test("finance runs settlements and records the payout with a UTR", async ({ page, context }) => {
  await signIn(context, "finance")
  await open(page, "marketplace-sellers")
  await section(page, "Settlements")
  await expect(page.getByText("No settlements yet")).toBeVisible()
  await page.getByRole("button", { name: "Run settlements" }).click()
  await expect(toast(page, "1 settlement created")).toBeVisible()
  const row = page.getByRole("row", { name: /Kavya Textiles/ })
  await expect(row.getByText("Sales")).toBeVisible()
  await expect(row.getByText("TCS (GST s.52)")).toBeVisible()
  await axe(page)
  await row.getByRole("button", { name: /Record payment/ }).click()
  const dialog = page.getByRole("dialog")
  const confirm = dialog.getByRole("button", { name: "Mark paid" })
  await dialog.getByLabel(/UTR/).fill("short1")
  await expect(confirm).toBeDisabled()
  await dialog.getByLabel(/UTR/).fill("hdfcn52026110512345")
  await expect(confirm).toBeEnabled()
  await confirm.click()
  await expect(toast(page, /marked paid/)).toBeVisible()
  await expect(row.getByText("UTR HDFCN52026110512345")).toBeVisible()
  // Nothing left to pay out: a second run creates nothing.
  await page.getByRole("button", { name: "Run settlements" }).click()
  await expect(toast(page, "Nothing payable yet")).toBeVisible()
})

test("settings: the owner sees defaults and the tax-adviser note; staff can only read", async ({ browser }) => {
  const staff = await browser.newContext()
  await signIn(staff, "staff")
  const sp = await staff.newPage()
  await open(sp, "marketplace-sellers")
  await section(sp, "Settings")
  await expect(sp.getByLabel("TCS (%)")).toBeDisabled()
  await expect(sp.getByText("Only the owner can change these.")).toBeVisible()
  await staff.close()

  const owner = await browser.newContext()
  await signIn(owner, "owner")
  const page = await owner.newPage()
  await open(page, "marketplace-sellers")
  await section(page, "Settings")
  await expect(page.getByText(/Confirm the TCS and TDS rates/)).toBeVisible()
  await expect(page.getByText(/Default 0.5%/)).toBeVisible()
  await axe(page)
  const save = page.getByRole("button", { name: "Save changes" })
  await expect(save).toBeDisabled()
  await page.getByLabel("Commission (%)").fill("14")
  await save.click()
  await expect(toast(page, "Marketplace settings saved")).toBeVisible()
  await page.reload()
  await page.waitForFunction(() => !document.querySelector('main [role="status"][aria-busy="true"]'))
  await section(page, "Settings")
  await expect(page.getByLabel("Commission (%)")).toHaveValue("14")
  await owner.close()
})
